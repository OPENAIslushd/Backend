// Opens the running Orchestrator to the internet through ngrok, behind HTTP basic auth.
// Credentials are generated once into .ngrok/policy.yml (git-ignored, owner-only) and reused.
const { spawn } = require("node:child_process");
const { randomBytes } = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const dir = path.join(__dirname, "../.ngrok");
const policy = path.join(dir, "policy.yml");
const port = process.env.PORT || "3001";
if (!fs.existsSync(policy)) {
  fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
  const user = "slushd";
  const password = randomBytes(15).toString("base64url");
  fs.writeFileSync(
    policy,
    `# Generated by scripts/tunnel.cjs. Share these credentials only with people who should use the demo.
on_http_request:
  - actions:
      - type: basic-auth
        config:
          credentials:
            - "${user}:${password}"
`,
    { mode: 0o600 },
  );
}
const credentials = fs.readFileSync(policy, "utf8").match(/- "([^"]+)"/)?.[1];
console.log(
  `ngrok tüneli localhost:${port} için açılıyor. Kullanıcı:şifre → ${credentials}\n(.ngrok/policy.yml içinde saklanır; yenisi için dosyayı silin.)`,
);
const child = spawn("ngrok", ["http", port, "--traffic-policy-file", policy], {
  stdio: "inherit",
});
child.on("error", () => {
  console.error(
    "ngrok bulunamadı. Kurulum: brew install ngrok/ngrok/ngrok, sonra ngrok config add-authtoken <token>",
  );
  process.exitCode = 1;
});
child.on("exit", (code) => (process.exitCode = code ?? 0));
