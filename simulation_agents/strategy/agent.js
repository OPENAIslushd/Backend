import { CHANNELS, CREATIVE_FACTORS, digest, rng, scope, checkStrategy } from '../shared/core.js';
import { validateDefinition } from '../shared/contracts.js';

export function generate(request) {
  const { input, candidate_count = 150, seed = 42, revision = 1 } = request.payload;
  const random = rng({ seed, input, revision, run_id: request.run_id });
  const anchors = [[0.8, 0.1, 0.1], [0.1, 0.8, 0.1], [0.1, 0.1, 0.8], [0.34, 0.33, 0.33]];
  const strategies = [];
  for (let i = 0; i < candidate_count; i++) {
    let weights = anchors[i];
    if (!weights) {
      const draws = CHANNELS.map(() => -Math.log(Math.max(random(), 1e-12)));
      const total = draws.reduce((a, b) => a + b, 0);
      weights = draws.map(v => 0.1 + 0.7 * v / total);
    }
    const creative = Object.keys(CREATIVE_FACTORS)[i % 3];
    const strategy = {
      strategy_id: `str-${digest({ run_id: request.run_id, input, seed, index: i }).slice(0, 24)}`,
      revision, run_id: request.run_id, ...scope(input), name: `${creative} campaign ${i + 1}`,
      generator: 'deterministic-diversity-v1', budget: input.budget, currency: input.currency,
      objective: 'purchases', audience: input.audience, region: input.region, start_day: 1, end_day: 30,
      initial_allocation: Object.fromEntries(CHANNELS.map((c, index) => [c, weights[index]])), creative,
      assumptions: [...input.assumptions, 'Generated by deterministic sampling, not an AI model.', 'Creative effects are illustrative model assumptions, not measured causal estimates.'],
      adaptation: {
        enabled: true, checkpoint_days: 3, max_reallocation_fraction: i % 3 === 0 ? 0.1 : 0.2,
        min_clicks_per_channel: i % 2 === 0 ? 30 : 60, min_purchases_per_channel: 3, exploration_floor: 0.1
      }
    };
    validateDefinition('strategy', strategy);
    checkStrategy(strategy, input, request.run_id);
    strategies.push(strategy);
  }
  return { generator: 'deterministic-diversity-v1', seed, revision, input, strategies };
}
